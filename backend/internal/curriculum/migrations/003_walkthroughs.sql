CREATE TABLE IF NOT EXISTS walkthroughs (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 class_id BIGINT NOT NULL,
 created_by BIGINT NOT NULL,
 assignment_id BIGINT NOT NULL,
 subject VARCHAR(16) NOT NULL,
 title VARCHAR(120) NOT NULL,
 question TEXT NOT NULL,
 reference_answer TEXT NOT NULL,
 client_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 stage VARCHAR(16) NOT NULL DEFAULT 'read',
 version INT NOT NULL DEFAULT 1,
 summary TEXT NOT NULL,
 improvements_json JSON NOT NULL,
 active_token VARCHAR(64) NOT NULL DEFAULT '',
 lease_until DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY uq_walk_request(class_id,created_by,client_key),
 INDEX idx_walk_owner(class_id,created_by,subject,id),
 FOREIGN KEY(class_id) REFERENCES classes(id),
 FOREIGN KEY(created_by) REFERENCES users(id),
 FOREIGN KEY(assignment_id) REFERENCES grade_assignments(id)
);
CREATE TABLE IF NOT EXISTS walkthrough_turns (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 walkthrough_id BIGINT NOT NULL,
 class_id BIGINT NOT NULL,
 created_by BIGINT NOT NULL,
 client_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 input_hash CHAR(64) NOT NULL,
 content TEXT NOT NULL,
 action VARCHAR(16) NOT NULL,
 stage_before VARCHAR(16) NOT NULL,
 stage_after VARCHAR(16) NOT NULL,
 response TEXT NOT NULL,
 summary TEXT NOT NULL,
 improvements_json JSON NOT NULL,
 status VARCHAR(16) NOT NULL,
 run_token VARCHAR(64) NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY uq_walk_turn(walkthrough_id,client_key),
 FOREIGN KEY(walkthrough_id) REFERENCES walkthroughs(id) ON DELETE CASCADE,
 FOREIGN KEY(class_id) REFERENCES classes(id),
 FOREIGN KEY(created_by) REFERENCES users(id)
);
