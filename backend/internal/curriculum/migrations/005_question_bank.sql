CREATE TABLE IF NOT EXISTS question_drafts (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 class_id BIGINT NOT NULL,
 created_by BIGINT NOT NULL,
 subject VARCHAR(16) NOT NULL,
 input_json JSON NOT NULL,
 questions_json JSON NOT NULL,
 citations_json JSON NOT NULL,
 bank_ids_json JSON NOT NULL,
 client_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 input_hash CHAR(64) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'pending',
 version INT NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY uq_question_draft(class_id,created_by,client_key),
 INDEX idx_question_draft_owner(class_id,created_by,subject,id),
 FOREIGN KEY(class_id) REFERENCES classes(id),
 FOREIGN KEY(created_by) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS bank_questions (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 class_id BIGINT NOT NULL,
 created_by BIGINT NOT NULL,
 subject VARCHAR(16) NOT NULL,
 origin_draft_id BIGINT NOT NULL,
 question_json JSON NOT NULL,
 citations_json JSON NOT NULL,
 stem TEXT NOT NULL,
 stem_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 version INT NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY uq_bank_stem(class_id,created_by,subject,stem_hash),
 INDEX idx_bank_owner(class_id,created_by,subject,id),
 FOREIGN KEY(class_id) REFERENCES classes(id),
 FOREIGN KEY(created_by) REFERENCES users(id),
 FOREIGN KEY(origin_draft_id) REFERENCES question_drafts(id)
);
CREATE TABLE IF NOT EXISTS paper_drafts (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 class_id BIGINT NOT NULL,
 created_by BIGINT NOT NULL,
 subject VARCHAR(16) NOT NULL,
 title VARCHAR(120) NOT NULL,
 items_json JSON NOT NULL,
 total_score INT NOT NULL,
 client_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 input_hash CHAR(64) NOT NULL,
 version INT NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY uq_paper_request(class_id,created_by,client_key),
 INDEX idx_paper_owner(class_id,created_by,subject,id),
 FOREIGN KEY(class_id) REFERENCES classes(id),
 FOREIGN KEY(created_by) REFERENCES users(id)
);
