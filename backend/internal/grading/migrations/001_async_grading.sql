CREATE TABLE IF NOT EXISTS grade_assignments (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 class_id BIGINT NOT NULL,
 created_by BIGINT NOT NULL,
 title VARCHAR(120) NOT NULL,
 question TEXT NOT NULL,
 expected_answer TEXT NOT NULL,
 max_score INT NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 INDEX idx_grade_assignments_class(class_id,id),
 FOREIGN KEY(class_id) REFERENCES classes(id),
 FOREIGN KEY(created_by) REFERENCES users(id),
 CHECK(max_score BETWEEN 1 AND 100)
);
CREATE TABLE IF NOT EXISTS submissions (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 class_id BIGINT NOT NULL,
 assignment_id BIGINT NOT NULL,
 student_id BIGINT NOT NULL,
 created_by BIGINT NOT NULL,
 client_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 answer MEDIUMTEXT NOT NULL,
 answer_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY uq_submission(student_id,assignment_id,client_key),
 INDEX idx_submissions_class(class_id,id),
 FOREIGN KEY(assignment_id) REFERENCES grade_assignments(id),
 FOREIGN KEY(student_id) REFERENCES users(id),
 FOREIGN KEY(class_id) REFERENCES classes(id)
);
CREATE TABLE IF NOT EXISTS grade_tasks (
 task_id CHAR(32) CHARACTER SET ascii PRIMARY KEY,
 submission_id BIGINT NOT NULL UNIQUE,
 class_id BIGINT NOT NULL,
 created_by BIGINT NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'pending',
 attempts INT NOT NULL DEFAULT 0,
 idempotency_key VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 error VARCHAR(64) NOT NULL DEFAULT '',
 run_token CHAR(32) CHARACTER SET ascii NULL,
 lease_until DATETIME(6) NULL,
 available_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 started_at DATETIME(6) NULL,
 finished_at DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 INDEX idx_grade_tasks_pending(status,available_at),
 INDEX idx_grade_tasks_class(class_id,created_by),
 FOREIGN KEY(submission_id) REFERENCES submissions(id) ON DELETE CASCADE,
 CHECK(status IN ('pending','running','succeeded','failed'))
);
CREATE TABLE IF NOT EXISTS grade_results (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 submission_id BIGINT NOT NULL,
 class_id BIGINT NOT NULL,
 created_by BIGINT NOT NULL,
 idempotency_key VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 score INT NOT NULL,
 max_score INT NOT NULL,
 feedback TEXT NOT NULL,
 prompt_tokens INT NOT NULL,
 completion_tokens INT NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(submission_id) REFERENCES submissions(id) ON DELETE CASCADE,
 CHECK(score>=0 AND score<=max_score)
);
CREATE TABLE IF NOT EXISTS grade_outbox (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 task_id CHAR(32) CHARACTER SET ascii NOT NULL,
 kind VARCHAR(16) NOT NULL,
 generation INT NOT NULL,
 state VARCHAR(16) NOT NULL DEFAULT 'pending',
 claim_token CHAR(32) CHARACTER SET ascii NULL,
 lease_until DATETIME(6) NULL,
 publish_attempts INT NOT NULL DEFAULT 0,
 available_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 published_at DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY uq_grade_event(task_id,kind,generation),
 INDEX idx_outbox_due(state,available_at,lease_until),
 FOREIGN KEY(task_id) REFERENCES grade_tasks(task_id) ON DELETE CASCADE
);
